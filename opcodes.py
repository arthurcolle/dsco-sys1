"""Op-code vocabulary for autonomous agent mechanics.

    .venv/bin/python opcodes.py            # writes opcodes.json, checks invariants

Each op-code is one reserved token the System One model can read or emit
("functional tokens", cf. Octopus v2, arXiv:2404.01744). An entry records:

  code       stable integer id (0..N-1), assigned in table order
  mnemonic   FAMILY.VERB.OBJECT or FAMILY.NAME
  token      <|op:family.verb.object|>
  family     one of FAMILIES below
  desc       one-sentence semantics
  operands   typed parameters, name:type
  effect     pure | observe | local | egress | control
             (pure = internal reasoning; observe = read-only; local = changes
             local state; egress = reaches outside the machine; control =
             changes the agent's own governance or lifecycle)
  dsco       the dsco tool or chronicle event it corresponds to, if any

Pairs are curated per object: only verbs that make sense for that object are
listed, so every combination has a definite meaning.
"""
