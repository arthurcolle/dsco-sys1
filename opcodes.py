MNEMONIC = re.compile(r"^[A-Z]+(\.[A-Z0-9_]+){1,2}$")


ARTICLE_BEFORE = re.compile(r"\b(a|an|the|current|every|each|new|existing|running|failed|stored|paused|finished|single|available|several|independent|dependent|all)\s+\{o\}")


def phrase(template: str, odesc: str) -> str:
    """Fill a verb template without doubled articles; fix a/an."""
    if ARTICLE_BEFORE.search(template):
        odesc = re.sub(r"^(a|an|the)\s+", "", odesc)
    elif not re.match(r"^(a|an|the)\s", odesc) and not template.startswith("{o}"):
        odesc = "the " + odesc
    text = template.format(o=odesc)
    text = re.sub(r"\b([Aa]) ([aeiouAEIOU]|HTTP|MCP|SQL|URL|LLM)", lambda m: ("an " if m.group(1) == "a" else "An ") + m.group(2), text)
    return text[0].upper() + text[1:]


def build() -> list[dict]:
    ops = []
    for family, (_, objects, singles) in FAMILIES.items():
        for name, desc, operands, effect in singles:
            ops.append({"mnemonic": f"{family}.{name}", "family": family, "desc": desc,
                        "operands": operands, "effect": effect})
        for obj, (odesc, verbs) in objects.items():
            for verb in verbs:
                template, operands, effect = VERBS[verb]
                ops.append({"mnemonic": f"{family}.{verb.upper()}.{obj.upper()}", "family": family,
                            "desc": phrase(template, odesc), "operands": operands, "effect": effect})
    for code, op in enumerate(ops):
        op["code"] = code
        op["token"] = "<|op:" + op["mnemonic"].lower() + "|>"
        op["dsco"] = DSCO_GROUNDING.get(op["mnemonic"])
    return ops


def check(ops: list[dict]) -> None:
    mnemonics = [o["mnemonic"] for o in ops]
    dupes = [m for m, n in __import__("collections").Counter(mnemonics).items() if n > 1]
    assert not dupes, f"duplicate mnemonics: {dupes[:10]}"
    assert all(MNEMONIC.match(m) for m in mnemonics), [m for m in mnemonics if not MNEMONIC.match(m)][:5]
    assert all(o["effect"] in {"pure", "observe", "local", "egress", "control"} for o in ops)
    missing = sorted(set(DSCO_GROUNDING) - set(mnemonics))
    assert not missing, f"grounding refers to unknown op-codes: {missing}"
    assert len(ops) == TARGET, f"{len(ops)} op-codes, expected {TARGET}"


def main() -> int:
    ops = build()
    counts = __import__("collections").Counter(o["family"] for o in ops)
    print(json.dumps({"total": len(ops), "families": dict(counts)}))
    check(ops)
    out = Path(__file__).with_name("opcodes.json")
    out.write_text(json.dumps({"version": 1, "count": len(ops), "ops": ops}, indent=1, ensure_ascii=False))
    print(f"wrote {out} ({len(ops)} op-codes, {sum(1 for o in ops if o['dsco'])} grounded in dsco)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
